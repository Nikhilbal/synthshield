
"""
SYNTHSHIELD
Stage 8.4.2 B2 - Signed PostgreSQL Event Storage

New security events are signed using HMAC-SHA256
before being inserted into PostgreSQL.

Existing historical events remain unchanged.
"""

from datetime import datetime
from typing import Any
from uuid import UUID

from psycopg.rows import dict_row

from src.database import get_database_connection
from src.integrity import sign_security_event


# =========================================================
# SAVE SECURITY EVENT TO POSTGRESQL
# =========================================================

def save_security_event(event: dict[str, Any]) -> bool:
    """
    Save a security event and its HMAC integrity tag.

    Returns:
        True  - A new event was inserted.
        False - The event ID already exists.

    The integrity tag is generated by the application,
    not trusted from the caller's input.
    """

    # -----------------------------------------------------
    # STEP 1: GENERATE HMAC-SHA256 INTEGRITY TAG
    # -----------------------------------------------------

    integrity_tag = sign_security_event(event)

    # -----------------------------------------------------
    # STEP 2: PREPARE SQL INSERT STATEMENT
    # -----------------------------------------------------

    sql = """
        INSERT INTO security_events (
            event_id,
            timestamp_utc,
            agent_id,
            source_names,
            source_count,
            sensitive_inference,
            purpose_drift,
            risk_level,
            decision,
            integrity_tag
        )
        VALUES (
            %s, %s, %s, %s, %s,
            %s, %s, %s, %s, %s
        )
        ON CONFLICT (event_id) DO NOTHING
    """

    # -----------------------------------------------------
    # STEP 3: PREPARE DATABASE VALUES
    # -----------------------------------------------------

    values = (
        UUID(str(event["event_id"])),
        datetime.fromisoformat(
            event["timestamp_utc"]
        ),
        event["agent_id"],
        event["source_names"],
        event["source_count"],
        event["sensitive_inference"],
        event["purpose_drift"],
        event["risk_level"],
        event["decision"],
        integrity_tag,
    )

    # -----------------------------------------------------
    # STEP 4: INSERT EVENT INTO POSTGRESQL
    # -----------------------------------------------------

    with get_database_connection() as connection:

        with connection.cursor() as cursor:

            cursor.execute(
                sql,
                values,
            )

            inserted = cursor.rowcount == 1

    return inserted


# =========================================================
# RETRIEVE SECURITY EVENT FROM POSTGRESQL
# =========================================================

def get_security_event(
    event_id: str,
) -> dict[str, Any] | None:
    """
    Retrieve one security event.

    Includes the stored integrity tag so that
    later stages can verify its authenticity.

    This function does NOT verify HMAC yet.
    """

    sql = """
        SELECT
            event_id,
            timestamp_utc,
            agent_id,
            source_names,
            source_count,
            sensitive_inference,
            purpose_drift,
            risk_level,
            decision,
            integrity_tag,
            recorded_at
        FROM security_events
        WHERE event_id = %s
    """

    with get_database_connection() as connection:

        with connection.cursor(
            row_factory=dict_row
        ) as cursor:

            cursor.execute(
                sql,
                (UUID(str(event_id)),),
            )

            event = cursor.fetchone()

    return event
